export const ENTITY_ICON_NAMES: ReadonlySet<string> = new Set(Object.keys(COMPONENTS));

export const DEFAULT_ENTITY_ICON: Record<'subject' | 'object' | 'organization', string> = {
  subject: 'UserRound',
  object: 'Laptop',
  organization: 'Building2',
};

interface EntityIconGlyphProps {
  name?: string;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
  kind?: 'subject' | 'object' | 'organization';
}

export function EntityIconGlyph({ name, size = 18, strokeWidth = 1.5, className, style, kind }: EntityIconGlyphProps) {
  const fallback =
    kind === 'object'
      ? COMPONENTS[DEFAULT_ENTITY_ICON.object]
      : kind === 'organization'
        ? COMPONENTS[DEFAULT_ENTITY_ICON.organization]
        : COMPONENTS[DEFAULT_ENTITY_ICON.subject];
  const Cmp = (name && COMPONENTS[name]) || fallback || UserRound;
  return <Cmp size={size} strokeWidth={strokeWidth} className={className} style={style} />;
}
